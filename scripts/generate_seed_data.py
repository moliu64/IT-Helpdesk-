def main() -> None:
    knowledge = ROOT / "data" / "knowledge"
    tickets_dir = ROOT / "data" / "tickets"
    knowledge.mkdir(parents=True, exist_ok=True)
    tickets_dir.mkdir(parents=True, exist_ok=True)
    for index, (title, symptom, steps) in enumerate(KB, 1):
        body = f"# {title}\n\n## 症状\n\n{symptom}\n\n## 解决步骤\n\n" + "\n".join(f"{i}. {step}" for i, step in enumerate(steps, 1)) + "\n"
        (knowledge / f"KB-{index:04d}.md").write_text(body, encoding="utf-8")

    # Keep P1 limited to organization-wide outage / business-blocking incidents.
    p1_titles = {"办公区断网", "勒索提示弹窗", "新员工设备准备"}
    remaining_priorities = iter(["P2"] * 13 + ["P3"] * 29 + ["P4"] * 19)
    tickets = []
    counter = 0
    for category, titles in CATEGORIES.items():
        for title in titles:
            priority = "P1" if title in p1_titles else next(remaining_priorities)
            descriptions, resolutions = ticket_details(title, category, priority)
            tickets.append({
                "ticket_id": f"HIST-{counter + 1:04d}",
                "title": title,
                "description": descriptions,
                "category": category,
                "priority": priority,
                "resolution": resolutions,
            })
            counter += 1
    (tickets_dir / "historical_tickets.json").write_text(json.dumps(tickets, ensure_ascii=False, indent=2), encoding="utf-8")
    print(f"generated {len(KB)} KB articles and {len(tickets)} tickets")

